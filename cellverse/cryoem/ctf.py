"""
This module provides methods for dealing with Contrast Transfer Function (CTF).
"""

from __future__ import annotations

from dataclasses import (
    dataclass,
    fields,
)
from enum import Enum
from typing import Final

import torch

from cellverse.math_utils import ht_object
from cellverse.math_utils.grid import get_frequency_grid
from cellverse.math_utils.helper import to_2tuple
from cellverse.math_utils.radial import get_frequency_radial_grid

